def as_bool(value: Any, default: bool = False) -> bool:
    """宽松解析布尔值类型。"""
    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        return value.strip().lower() in {"true", "1", "yes", "y", "是"}
    if isinstance(value, (int, float)):
        return bool(value)
    return default
